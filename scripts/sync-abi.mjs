// Copies the compiled OrderveilCommitments ABI + bytecode from Foundry output into src/.
// Run after `forge build` in contracts/: npm run contracts:abi
import fs from 'node:fs'
const art = JSON.parse(fs.readFileSync(new URL('../contracts/out/OrderveilCommitments.sol/OrderveilCommitments.json', import.meta.url), 'utf8'))
const out = `// Generated by scripts/sync-abi.mjs from contracts/out — do not edit by hand.
export const orderveilCommitmentsAbi = ${JSON.stringify(art.abi, null, 2)}

export const orderveilCommitmentsBytecode = '${art.bytecode.object}'
`
fs.writeFileSync(new URL('../src/contracts/orderveilCommitments.js', import.meta.url), out)
console.log('ABI entries:', art.abi.length)
